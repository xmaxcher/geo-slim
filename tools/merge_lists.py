#!/usr/bin/env python3
"""Merge curated + community foreign-domain lists into one router list."""
import re
import sys
import urllib.request

CURATED = sys.argv[1]
OUT = sys.argv[2]

RAW = "https://raw.githubusercontent.com"
ITDOG = f"{RAW}/itdoginfo/allow-domains/main"
SOURCES = [
    ("no-russia-hosts (владельцы режут российские IP)", [f"{RAW}/dartraiden/no-russia-hosts/master/hosts.txt"]),
    ("itdog: geoblock (сервисы, закрывшие доступ из РФ)", [f"{ITDOG}/Categories/geoblock.lst"]),
    ("itdog: сервисы", [f"{ITDOG}/Services/{n}.lst" for n in (
        "cloudflare", "cloudfront", "digitalocean", "hetzner", "ovh", "discord", "meta", "google_ai",
        "google_meet", "google_play", "roblox", "telegram", "tiktok", "twitter", "youtube")]),
]
V2FLY = f"{RAW}/v2fly/domain-list-community/master/data"
V2FLY_ROOTS = ["category-ai-!cn"]

DOMAIN_RE = re.compile(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)*\.[a-z][a-z0-9-]*[a-z0-9]$")
RU_TLDS = (".ru", ".su", ".xn--p1ai", ".moscow", ".xn--80adxhks", ".xn--d1acj3b", ".tatar")
# российские сервисы на доменах вне .ru — точные суффиксы (корень вида «max»/«mail» задел бы max.com, mail.com)
RU_DOMAINS = {
    "yandex.com", "yandex.net", "yastatic.net", "yandexcloud.net", "yandex.cloud", "yandex.st", "ya.cc",
    "vk.com", "vk.me", "vkuser.net", "userapi.com", "vk-portal.net", "mycdn.me", "vkontakte.com",
    "2gis.com", "kaspersky.com", "kaspersky-labs.com", "qiwi.com", "habr.com", "okko.tv", "avito.st",
    "sberbank.com", "sber.io", "tinkoff.com", "ozon.travel", "wildberries.am", "dzen.com", "rutube.tv",
    "kinopoisk.dev", "mail.com.ru", "ivi.tv", "start.film", "premier.one", "wink.tv", "more.tv",
}


def fetch(url: str) -> str:
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.read().decode("utf-8", "replace")
    except Exception as e:  # noqa: BLE001 — источник недоступен = просто пропускаем
        print(f"  ! {url}: {e}", file=sys.stderr)
        return ""


def norm(line: str) -> str | None:
    line = line.split("#", 1)[0].strip().lower()
    if not line:
        return None
    line = re.sub(r"^(\*\.|\*|domain:|full:|\.)", "", line)
    line = line.split("@", 1)[0].split(":", 1)[0].strip()
    return line if DOMAIN_RE.match(line) else None


def v2fly(name: str, seen: set[str]) -> set[str]:
    if name in seen:
        return set()
    seen.add(name)
    out: set[str] = set()
    for raw in fetch(f"{V2FLY}/{name}").splitlines():
        s = raw.split("#", 1)[0].strip()
        if not s:
            continue
        if s.startswith("include:"):
            out |= v2fly(s.split(":", 1)[1].split()[0].strip(), seen)
        elif s.startswith(("regexp:", "keyword:")):
            continue
        else:
            d = norm(s)
            if d:
                out.add(d)
    return out


def is_ru(d: str) -> bool:
    return d.endswith(RU_TLDS) or any(d == r or d.endswith("." + r) for r in RU_DOMAINS)


curated_text = open(CURATED, encoding="utf-8").read()
curated = {d for d in (norm(l) for l in curated_text.splitlines()) if d}

groups: list[tuple[str, set[str]]] = []
for title, urls in SOURCES:
    s: set[str] = set()
    for u in urls:
        s |= {d for d in (norm(l) for l in fetch(u).splitlines()) if d}
    groups.append((title, s))
groups.append(("v2fly: нейросети вне Китая (category-ai-!cn)", set().union(*(v2fly(r, set()) for r in V2FLY_ROOTS))))

dropped_ru: set[str] = set()
taken = set(curated)
blocks = []
for title, s in groups:
    clean = set()
    for d in s:
        if is_ru(d):
            dropped_ru.add(d)
        elif d not in taken:
            clean.add(d)
    taken |= clean
    blocks.append((title, clean))


def covered(d: str, pool: set[str]) -> bool:
    parts = d.split(".")
    return any(".".join(parts[i:]) in pool for i in range(1, len(parts) - 1))


final_pool = taken
lines = [
    "# GENERATED by tools/merge_lists.py - do NOT edit. Edit lists/manual.txt instead.",
    "# = lists/manual.txt + community lists of services that block Russian IPs (sources below).",
    "",
    curated_text.rstrip("\n"),
    "",
]
total = len(curated)
for title, s in blocks:
    keep = sorted(d for d in s if not covered(d, final_pool))
    if not keep:
        continue
    lines.append(f"# === {title} — {len(keep)} доменов (собрано автоматически) ===")
    lines.extend(keep)
    lines.append("")
    total += len(keep)
# источники сломались или недоступны — не затираем рабочий список почти пустым
if total - len(curated) < 500:
    print(f"ERROR: из внешних источников собрано всего {total - len(curated)} доменов", file=sys.stderr)
    sys.exit(1)
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"ручных: {len(curated)}; всего доменов: {total}; выкинуто российских: {len(dropped_ru)}")
for title, s in blocks:
    print(f"  {title}: +{len([d for d in s if not covered(d, final_pool)])}")
print("примеры выкинутых RU:", sorted(dropped_ru)[:25])
